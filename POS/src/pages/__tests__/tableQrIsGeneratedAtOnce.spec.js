/**
 * //// Neoffice — added file (no upstream equivalent). The QR code of a table is generated at once (NeoRestau lot 1, Daniel, 01.11: he pressed the small QR of a table and got a dialog, « Open this table for QR
 * //// self-ordering? », with a « Generate QR » button to press; « il faut que ça génère directement le QR »). The sale page is too big to mount for one gesture, so the handler is read from its source.
 * @vitest-environment node
 */
import { readFileSync } from "node:fs"
import path from "node:path"
import { describe, expect, it } from "vitest"

const source = readFileSync(path.resolve(__dirname, "../POSSale.vue"), "utf8")
const handler = source.slice(
	source.indexOf("async function handleQRButtonClick"),
	source.indexOf("async function confirmQRGeneration"),
)

describe("the QR code of a table", () => {
	it("is generated by the press on the table's QR, with no confirmation dialog first", () => {
		expect(handler).toContain("await confirmQRGeneration()")
		expect(handler).not.toContain("showQRConfirmDialog.value = true")
	})

	it("still shows the code at once for a table that already has one", () => {
		expect(handler).toContain("activeQRTokens.value.has(tableName)")
		expect(handler).toContain("showQRDialog.value = true")
	})

	it("generates the code of the table that was pressed, not the cart's", () => {
		expect(handler).toContain("qrTable.value = table")
	})
})
